#!/usr/bin/env python3
"""
tools/seo.py : one-command SEO builder for the static site.

Usage:
    python tools/seo.py https://your-domain.netlify.app
    (optional) GSC_TOKEN=xxxx python tools/seo.py https://your-domain.netlify.app   # adds the Google Search Console tag

What it does (safe to re-run any time):
  1. Injects/refreshes a <!-- SEO:BEGIN --> ... <!-- SEO:END --> block in the <head> of every page
     (canonical URL, og:url, robots, theme-color, manifest, favicons, JSON-LD structured data).
  2. Regenerates sitemap.xml and robots.txt with the absolute domain.
Structured data written: ProfessionalService (home), WebSite, BreadcrumbList (inner pages),
FAQPage (/faq/), WebApplication (calculators).
"""
import sys, re, json, glob, os, datetime, html

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
# Without a domain the canonical / og URLs stay root-relative (valid, but absolute is better).
# sitemap.xml and robots.txt NEED the real domain, so run this tool again once you know it.
SITE = (sys.argv[1] if len(sys.argv) > 1 else "").rstrip("/")
SMSITE = SITE or "https://YOUR-DOMAIN.netlify.app"
GSC = os.environ.get("GSC_TOKEN", "")   # optional: Google Search Console HTML-tag verification token
NAME_BN = "আল-আমিন ডিজিটাল ল্যান্ড সার্ভে"
NAME_EN = "Al-Amin Digital Land Survey"
PHONE = "+8801745473151"
SOCIAL = [
    "https://www.facebook.com/convincing.alamin11",
    "https://youtube.com/@convincing.alamin",
    "https://instagram.com/convincing.alamin/",
    "https://t.me/convincingalamin",
    "https://linkedin.com/in/convincing-al-amin/",
]
CALCULATORS = {"/calculators/land-area/", "/calculators/faraiz/", "/calculators/ana-gonda-hissa/",
               "/calculators/deed-fee/", "/calculators/copy-fee/"}
SECTION_NAMES = {"services": "সেবা", "deeds": "দলিল", "calculators": "ক্যালকুলেটর", "learn": "জানুন"}

# Per-page title / description / keywords live in tools/seo-keywords.json (edit that file, then re-run this tool).
KW_FILE = os.path.join(os.path.dirname(os.path.abspath(__file__)), "seo-keywords.json")
KW = json.load(open(KW_FILE, encoding="utf8")) if os.path.exists(KW_FILE) else {}
BRAND = " | " + NAME_BN

def apply_meta(path, src):
    """Write the keyword-optimised title, description, Open Graph and Twitter tags from seo-keywords.json."""
    k = KW.get(path)
    if not k:
        return src
    title = html.escape(k["title"] + BRAND, quote=True)
    desc = html.escape(k["description"], quote=True)
    src = re.sub(r"<title>.*?</title>", "<title>%s</title>" % title, src, count=1, flags=re.S)
    src = re.sub(r'<meta name="description" content="[^"]*">', '<meta name="description" content="%s">' % desc, src, count=1)
    for key, val in (("og:title", title), ("og:description", desc)):
        src = re.sub(r'<meta property="%s" content="[^"]*">' % key, '<meta property="%s" content="%s">' % (key, val), src)
    for key, val in (("twitter:title", title), ("twitter:description", desc)):
        src = re.sub(r'<meta name="%s" content="[^"]*">' % key, '<meta name="%s" content="%s">' % (key, val), src)
    return src

def pages():
    """Yield (url_path, file_path) for every index.html page."""
    for f in sorted(glob.glob(os.path.join(ROOT, "**", "index.html"), recursive=True)):
        rel = os.path.relpath(f, ROOT).replace(os.sep, "/")
        if rel.startswith(("assets/", "tools/")):
            continue
        path = "/" + rel[: -len("index.html")]
        yield path, f

def strip_tags(s):
    return html.unescape(re.sub(r"<[^>]+>", "", s)).strip()

def build_block(path, src):
    title = strip_tags(re.search(r"<title>(.*?)</title>", src, re.S).group(1))
    m = re.search(r'<meta name="description" content="(.*?)">', src, re.S)
    desc = html.unescape(m.group(1)) if m else title
    h1m = re.search(r"<h1[^>]*>(.*?)</h1>", src, re.S)
    h1 = strip_tags(h1m.group(1)) if h1m else title
    url = SITE + path
    out = [
        "<!-- SEO:BEGIN (generated by tools/seo.py, do not edit by hand) -->",
        '<link rel="canonical" href="%s">' % url,
        '<meta property="og:url" content="%s">' % url,
        '<meta property="og:image" content="%s/assets/img/og-image.png">' % SITE,
        '<meta name="twitter:image" content="%s/assets/img/og-image.png">' % SITE,
        '<meta name="robots" content="index,follow,max-image-preview:large,max-snippet:-1">',
        '<meta name="theme-color" content="#0c2233">',
        '<meta name="author" content="%s">' % NAME_BN,
        ('<meta name="keywords" content="%s">' % html.escape(", ".join(KW[path]["keywords"]), quote=True)) if path in KW else "",
        '<link rel="manifest" href="/site.webmanifest">',
        '<link rel="icon" type="image/png" sizes="32x32" href="/assets/img/favicon-32.png">',
        '<link rel="icon" type="image/png" sizes="192x192" href="/assets/img/favicon-192.png">',
        '<link rel="apple-touch-icon" href="/assets/img/favicon-192.png">',
    ]
    if GSC:
        out.append('<meta name="google-site-verification" content="%s">' % GSC)
    graphs = []
    if path == "/":
        graphs.append({
            "@context": "https://schema.org", "@type": "ProfessionalService", "@id": SITE + "/#org",
            "name": NAME_BN, "alternateName": NAME_EN, "url": SITE + "/", "description": desc,
            "logo": SITE + "/assets/img/logo.png", "image": SITE + "/assets/img/og-image.png",
            "telephone": PHONE, "priceRange": "$",
            "areaServed": {"@type": "Country", "name": "Bangladesh"},
            "address": {"@type": "PostalAddress", "addressLocality": "Ghatail", "addressRegion": "Tangail", "addressCountry": "BD"},
            "availableLanguage": ["bn", "en"], "sameAs": SOCIAL,
            "contactPoint": {"@type": "ContactPoint", "telephone": PHONE, "contactType": "customer service", "availableLanguage": ["bn", "en"]},
        })
        graphs.append({"@context": "https://schema.org", "@type": "WebSite", "name": NAME_BN, "alternateName": NAME_EN,
                       "url": SITE + "/", "inLanguage": ["bn", "en"]})
    else:
        crumbs = [("হোম", SITE + "/")]
        parts = [p for p in path.strip("/").split("/") if p]
        if len(parts) > 1:
            top = parts[0]
            crumbs.append((SECTION_NAMES.get(top, top), SITE + "/" + top + "/"))
        crumbs.append((h1, url))
        graphs.append({"@context": "https://schema.org", "@type": "BreadcrumbList",
                       "itemListElement": [{"@type": "ListItem", "position": i + 1, "name": n, "item": u}
                                           for i, (n, u) in enumerate(crumbs)]})
    if path == "/faq/":
        qa = re.findall(r"<details><summary>(.*?)</summary><p>(.*?)</p></details>", src, re.S)
        graphs.append({"@context": "https://schema.org", "@type": "FAQPage", "mainEntity": [
            {"@type": "Question", "name": strip_tags(q), "acceptedAnswer": {"@type": "Answer", "text": strip_tags(a)}} for q, a in qa]})
    if path in CALCULATORS:
        graphs.append({"@context": "https://schema.org", "@type": "WebApplication", "name": h1, "url": url,
                       "applicationCategory": "UtilitiesApplication", "operatingSystem": "Any", "inLanguage": ["bn", "en"],
                       "offers": {"@type": "Offer", "price": "0", "priceCurrency": "BDT"}, "description": desc})
    for g in graphs:
        out.append('<script type="application/ld+json">%s</script>' % json.dumps(g, ensure_ascii=False))
    out.append("<!-- SEO:END -->")
    return "\n".join(l for l in out if l)

def main():
    urls = []
    for path, f in pages():
        src = open(f, encoding="utf8").read()
        src = re.sub(r"<!-- SEO:BEGIN.*?<!-- SEO:END -->\n?", "", src, flags=re.S)
        src = apply_meta(path, src)
        # remove tags that the SEO block now owns (avoid duplicates)
        src = re.sub(r'<meta property="og:image" content="[^"]*">', "", src)
        src = re.sub(r'<meta name="twitter:image" content="[^"]*">', "", src)
        src = re.sub(r'<link rel="apple-touch-icon" href="[^"]*">', "", src)
        src = re.sub(r'<link rel="icon" href="[^"]*">', "", src)
        src = src.replace("</head>", build_block(path, src) + "\n</head>", 1)
        open(f, "w", encoding="utf8").write(src)
        if os.path.basename(os.path.dirname(f)) != "404":
            urls.append(path)
    today = datetime.date.today().isoformat()
    prio = lambda p: "1.0" if p == "/" else ("0.9" if p.count("/") <= 2 else "0.7")
    sm = ['<?xml version="1.0" encoding="UTF-8"?>', '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">']
    for p in urls:
        sm.append("  <url><loc>%s%s</loc><lastmod>%s</lastmod><changefreq>monthly</changefreq><priority>%s</priority></url>" % (SMSITE, p, today, prio(p)))
    sm.append("</urlset>")
    open(os.path.join(ROOT, "sitemap.xml"), "w", encoding="utf8").write("\n".join(sm) + "\n")
    open(os.path.join(ROOT, "robots.txt"), "w", encoding="utf8").write(
        "User-agent: *\nAllow: /\nDisallow: /tools/\n\nSitemap: %s/sitemap.xml\n" % SMSITE)
    print("SEO built for %d pages, domain: %s" % (len(urls), SITE or "(none yet: run again with your domain: python tools/seo.py https://your-domain)"))

if __name__ == "__main__":
    main()
